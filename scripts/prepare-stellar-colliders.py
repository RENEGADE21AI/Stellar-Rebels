"""Bake the opaque parts of each sprite as compact, normalized rectangles.

Run after prepare-stellar-2d.py. Rows represent solids and preserve gaps between
wings, prongs and nearby modules. One soft edge or glowing pixel cannot create
a collision surface. The web build checks the source digests.
"""

import base64
import hashlib
import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1] / 'arcade'
SPRITES = ROOT / 'media' / 'sprites'
SMALL = ('scout', 'lancer', 'diver', 'sweeper', 'escort', 'relay', 'phantom', 'splitter', 'shard', 'rock', 'turret', 'shield-node')
LARGE = ('cruiser', 'gatekeeper', 'warden', 'matron', 'tyrant', 'siphon', 'wraith', 'crown')
PILOTS = ('kestrel', 'needle', 'bastion')
TITLE_MASK_SIZE = 128


def title_hit_mask(source):
    with Image.open(source) as image:
        alpha = image.getchannel('A').resize((TITLE_MASK_SIZE, TITLE_MASK_SIZE), Image.Resampling.BOX)
    mask = bytearray(TITLE_MASK_SIZE * TITLE_MASK_SIZE // 8)
    for index, value in enumerate(alpha.tobytes()):
        if value >= 110:
            mask[index // 8] |= 1 << (index % 8)
    return base64.b64encode(mask).decode('ascii')


def horizontal_runs(row, width):
    start = None
    for x, alpha in enumerate((*row, 0)):
        if alpha >= 149 and start is None:
            start = x
        elif alpha < 149 and start is not None:
            yield start, min(x, width)
            start = None


def solid_rectangles(source, cells):
    with Image.open(source) as image:
        if image.mode != 'RGBA' or image.width != image.height:
            raise ValueError(f'{source.name} needs a square RGBA frame')
        alpha = image.getchannel('A').resize((cells, cells), Image.Resampling.BOX)

    pixels = alpha.load()
    active = {}
    finished = []
    for y in range(cells + 1):
        spans = set(horizontal_runs((pixels[x, y] for x in range(cells)), cells)) if y < cells else set()
        for (left, right), top in list(active.items()):
            if (left, right) not in spans:
                finished.append((left, top, right, y))
                del active[left, right]
        for span in sorted(spans):
            active.setdefault(span, y)

    # Integers in thousandths of the rendered square, with the same center for physics and Canvas.
    shapes = [[round(1000 * v / cells - 500) for v in rect] for rect in finished]
    if not shapes:
        raise ValueError(f'No collision geometry for {source.name}')
    return shapes


def main():
    masks = {key: solid_rectangles(SPRITES / (key + '.png'), 56 if key in LARGE else 34)
             for key in (*PILOTS, *SMALL, *LARGE)}
    checked = (*PILOTS, *SMALL, *LARGE, 'wraith-ghost')
    hashes = {key: hashlib.sha256((SPRITES / (key + '.png')).read_bytes()).hexdigest() for key in checked}

    lines = ['// Generated by scripts/prepare-stellar-colliders.py from the published sprite alpha.',
             'export const spriteBodies = {']
    for key, shape in masks.items():
        lines.append(f'  {json.dumps(key)}: [')
        for i in range(0, len(shape), 6):
            lines.append('    ' + ', '.join(json.dumps(rect, separators=(',', ':')) for rect in shape[i:i + 6]) + ',')
        lines.append('  ],')
    lines.extend(('};', '', 'export const spriteColliderDigests = {'))
    lines.extend(f'  {json.dumps(key)}: {json.dumps(value)},' for key, value in hashes.items())
    lines.extend(('};', '', f'export const titleMaskSize = {TITLE_MASK_SIZE};', 'export const titleHitMasks = {'))
    lines.extend(f'  {json.dumps(key)}: {json.dumps(title_hit_mask(SPRITES / (key + ".png")))},' for key in PILOTS)
    lines.extend(('};', ''))
    (ROOT / 'silhouettes.mjs').write_text('\n'.join(lines), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
